# Write a function that accepts any number of integers and returns their sum.
def sum_all_integers(*numbers):
    total = 0
    for num in numbers:
        if isinstance(num, int):
            total += num
        else:
            print(f"Warning: '{num}' is not an integer and will be skipped.")
    return total

